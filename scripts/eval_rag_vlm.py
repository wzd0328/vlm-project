import argparse
import os
import random
import sys
import time

__package__ = None
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from rag.mm_rag_agent import MiniMindRAGAgent
from rag.retriever import TextRAGRetriever


def default_device() -> str:
    try:
        import torch

        return "cuda" if torch.cuda.is_available() else "cpu"
    except ModuleNotFoundError:
        return "cpu"


def init_model(args):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    from model.model_minimind import get_model_params
    from model.model_vlm import MiniMindVLM, VLMConfig

    tokenizer = AutoTokenizer.from_pretrained("./model")
    if args.load_from == "model":
        moe_path = "_moe" if args.use_moe else ""
        ckp = f"{args.save_dir}/{args.weight}_{args.hidden_size}{moe_path}.pth"
        model = MiniMindVLM(
            VLMConfig(
                hidden_size=args.hidden_size,
                num_hidden_layers=args.num_hidden_layers,
                use_moe=bool(args.use_moe),
            ),
            vision_model_path="./model/siglip2-base-p32-256-ve",
        )
        state_dict = torch.load(ckp, map_location=args.device)
        model.load_state_dict({k: v for k, v in state_dict.items() if "mask" not in k}, strict=False)
    else:
        model = AutoModelForCausalLM.from_pretrained(args.load_from, trust_remote_code=True)
        model.vision_encoder, model.processor = MiniMindVLM.get_vision_model("./model/siglip2-base-p32-256-ve")
    get_model_params(model, model.config)
    return model.half().eval().to(args.device), tokenizer, model.processor


def generate_answer(model, tokenizer, preprocess, args, prompt):
    from PIL import Image
    from transformers import TextStreamer

    from model.model_vlm import MiniMindVLM

    image = Image.open(args.image_path).convert("RGB")
    pixel_values = {k: v.to(args.device) for k, v in MiniMindVLM.image2tensor(image, preprocess).items()}
    image_token_prompt = prompt.replace("<image>", model.config.image_special_token * model.config.image_token_len)
    messages = [{"role": "user", "content": image_token_prompt}]
    inputs_text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
        open_thinking=bool(args.open_thinking),
    )
    inputs = tokenizer(inputs_text, return_tensors="pt", truncation=True).to(args.device)
    streamer = TextStreamer(tokenizer, skip_prompt=True, skip_special_tokens=True)
    st = time.time()
    generated_ids = model.generate(
        inputs=inputs["input_ids"],
        attention_mask=inputs["attention_mask"],
        max_new_tokens=args.max_new_tokens,
        do_sample=True,
        streamer=streamer,
        pad_token_id=tokenizer.pad_token_id,
        eos_token_id=tokenizer.eos_token_id,
        top_p=args.top_p,
        temperature=args.temperature,
        pixel_values=pixel_values,
    )
    gen_tokens = len(generated_ids[0]) - len(inputs["input_ids"][0])
    if args.show_speed:
        print(f"\n[Speed]: {gen_tokens / max(time.time() - st, 1e-6):.2f} tokens/s")


def main():
    parser = argparse.ArgumentParser(description="MiniMind-V RAG Chat")
    parser.add_argument("--index_dir", default="rag_index", help="RAG index generated by rag/build_index.py")
    parser.add_argument("--image_path", required=True, help="Input image path")
    parser.add_argument("--question", default="请描述这张图，并结合检索资料回答。")
    parser.add_argument("--top_k", type=int, default=4)
    parser.add_argument("--min_score", type=float, default=1e-6, help="Minimum retrieval cosine score.")
    parser.add_argument("--language", choices=["zh", "en"], default="zh")
    parser.add_argument("--dry_run", type=int, default=0, help="Only print retrieved context and prompt; do not load VLM.")
    parser.add_argument("--load_from", default="model", type=str)
    parser.add_argument("--save_dir", default="out", type=str)
    parser.add_argument("--weight", default="sft_vlm", type=str)
    parser.add_argument("--hidden_size", default=768, type=int)
    parser.add_argument("--num_hidden_layers", default=8, type=int)
    parser.add_argument("--use_moe", default=0, type=int, choices=[0, 1])
    parser.add_argument("--max_new_tokens", default=512, type=int)
    parser.add_argument("--temperature", default=0.7, type=float)
    parser.add_argument("--top_p", default=0.85, type=float)
    parser.add_argument("--show_speed", default=1, type=int)
    parser.add_argument("--device", default=default_device(), type=str)
    parser.add_argument("--open_thinking", default=0, type=int)
    args = parser.parse_args()

    random.seed(random.randint(1, 31415926))
    retriever = TextRAGRetriever.load(args.index_dir)
    agent = MiniMindRAGAgent(retriever, top_k=args.top_k, language=args.language, min_score=args.min_score)
    prompt, results = agent.build_prompt(args.question, image_token="<image>")

    print("[RAG Retrieval]")
    for idx, item in enumerate(results, start=1):
        print(f"{idx}. score={item['score']:.3f} source={item.get('source')} caption={item.get('caption')[:120]}")
    print("\n[RAG Prompt]\n" + prompt)
    if args.dry_run:
        return

    model, tokenizer, preprocess = init_model(args)
    print("\n🤖: ", end="")
    generate_answer(model, tokenizer, preprocess, args, prompt)


if __name__ == "__main__":
    main()
